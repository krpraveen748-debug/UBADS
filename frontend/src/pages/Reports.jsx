import { AlertTriangle, FileBarChart2 } from "lucide-react";
import { getCollectionStatus, getDataQualityReport } from "../api/endpoints.js";
import Badge from "../components/ui/Badge.jsx";
import Card from "../components/ui/Card.jsx";
import ResourceState from "../components/ui/ResourceState.jsx";
import { useApiResource } from "../hooks/useApiResource.js";

function KeyValueList({ entries }) {
  return (
    <div className="space-y-1.5">
      {entries.map(([label, value]) => (
        <div key={label} className="flex items-center justify-between text-xs">
          <span className="text-slate-500">{label}</span>
          <span className="text-slate-200">{value ?? "—"}</span>
        </div>
      ))}
    </div>
  );
}

export default function Reports() {
  const dataQuality = useApiResource(getDataQualityReport, []);
  const collectionStatus = useApiResource(getCollectionStatus, []);

  return (
    <div className="space-y-6">
      <div>
        <h2 className="text-xl font-semibold text-slate-100">Reports</h2>
        <p className="text-sm text-slate-500 mt-1">
          Research and data-quality reports, generated by <code className="text-slate-400">ml-service</code>.
        </p>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-2 gap-4">
        <Card title="Data Quality Report">
          <ResourceState
            resource={dataQuality}
            onReload={dataQuality.reload}
            notAvailableHint="Backed by ml-service/data_quality.py — run 'python feature_engineering.py --data-quality-report' locally, or wait for the backend to expose this endpoint."
          >
            {(data) => (
              <KeyValueList
                entries={[
                  ["Total Events", data.total_events],
                  ["Distinct Users", data.distinct_users],
                  ["Coverage Period", data.coverage_period ? `${data.coverage_period.span_days?.toFixed(2)} days` : "—"],
                  ["Total Feature Windows", data.total_feature_windows],
                ]}
              />
            )}
          </ResourceState>
        </Card>

        <Card title="Collection Status">
          <ResourceState
            resource={collectionStatus}
            onReload={collectionStatus.reload}
            notAvailableHint="Backed by ml-service/collection_status.py — run 'python feature_engineering.py --collection-status' locally, or wait for the backend to expose this endpoint."
          >
            {(data) => (
              <KeyValueList
                entries={[
                  ["Technical Sufficiency", data.technical_sufficiency?.is_sufficient ? "Yes" : "No"],
                  ["Research Sufficiency", data.research_sufficiency?.is_sufficient ? "Yes" : "No"],
                  ["Qualifying Users", data.research_sufficiency?.qualifying_users?.length ?? 0],
                ]}
              />
            )}
          </ResourceState>
        </Card>

        <Card title="ML Readiness">
          <ResourceState
            resource={collectionStatus}
            onReload={collectionStatus.reload}
            notAvailableHint="ML readiness is computed by ml-service/collection_status.py and is not yet exposed via the backend API."
          >
            {(data) => {
              const ready = data.decision === "READY_FOR_ML";
              return (
                <div className="space-y-2">
                  <Badge variant={ready ? "ok" : "warn"} className="text-xs px-2 py-1">
                    {ready ? "READY_FOR_ML" : "⚠ INSUFFICIENT_REAL_DATA"}
                  </Badge>
                  {!ready && data.research_sufficiency?.reasons?.length > 0 && (
                    <div>
                      <p className="text-xs text-slate-500 mt-2">Reason:</p>
                      <ul className="text-xs text-slate-400 list-disc list-inside space-y-1 mt-1">
                        {data.research_sufficiency.reasons.map((r, i) => (
                          <li key={i}>{r}</li>
                        ))}
                      </ul>
                    </div>
                  )}
                </div>
              );
            }}
          </ResourceState>
        </Card>

        <Card title="Behavioral Coverage">
          <ResourceState
            resource={dataQuality}
            onReload={dataQuality.reload}
            notAvailableHint="Per-category event coverage is not yet exposed via the backend API."
          >
            {(data) => (
              <KeyValueList
                entries={Object.entries(data.events_by_category || {}).map(([cat, count]) => [cat, count])}
              />
            )}
          </ResourceState>
        </Card>

        <Card title="Research Summary" className="lg:col-span-2">
          <ResourceState
            resource={collectionStatus}
            onReload={collectionStatus.reload}
            notAvailableHint="A combined research summary is not yet exposed via the backend API."
          >
            {(data) => (
              <div className="flex items-start gap-3">
                <AlertTriangle className="h-4 w-4 text-status-warn shrink-0 mt-0.5" />
                <p className="text-xs text-slate-400">
                  {data.decision === "READY_FOR_ML"
                    ? "Sufficient real, multi-day, human-attributed behavioral history exists to proceed toward model training."
                    : "The system does not yet have sufficient multi-day human-attributed behavioral history. This is preferable to showing fake readiness — continue collecting real activity across separate days (see Endpoint Enrollment)."}
                </p>
              </div>
            )}
          </ResourceState>
        </Card>
      </div>

      <Card>
        <div className="flex items-center gap-2 text-xs text-slate-500">
          <FileBarChart2 className="h-3.5 w-3.5" />
          These reports mirror the real, non-fabricated output of{" "}
          <code className="text-slate-400">ml-service/data_quality.py</code> and{" "}
          <code className="text-slate-400">ml-service/collection_status.py</code> — nothing here is computed
          independently by the frontend.
        </div>
      </Card>
    </div>
  );
}
